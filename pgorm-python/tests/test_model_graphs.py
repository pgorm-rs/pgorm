"""Relations, graphs, keyset cursors, pages and the version-reading writes of
declared models, against a live server: what each slot kind decodes, how a
relation's far end is found and loaded, and how a cursor and a paginator
walk the rows."""

import os
import unittest

import pgorm as p
from pgorm._registered.versions import Change, Inserted, Updated

SCHEMA = "python_graphs"
mood = p.TypeName("mood", schema=SCHEMA)

Account = p.Model(
    "account",
    {
        "id": p.Column("i64", primary_key=True, generated="by_default"),
        "name": p.Column("text"),
        "display_name": p.Column("text", nullable=True),
        "mood": p.Column(mood, nullable=True, values=["calm", "glad", "sour"]),
        "tags": p.Column("text", array=True, default=True),
        "visits": p.Column("i32", default=True),
        "seq": p.Column("i32", generated="always"),
    },
    schema=SCHEMA,
)
Post = p.Model(
    "post",
    {
        "id": p.Column("i64", primary_key=True),
        "author_id": p.Column("i64"),
        "editor_id": p.Column("i64", nullable=True),
        "title": p.Column("text"),
    },
    schema=SCHEMA,
)
Tag = p.Model("tag", {"id": p.Column("i32", primary_key=True), "label": p.Column("text")}, schema=SCHEMA)
PostTag = p.Model(
    "post_tag",
    {"post_id": p.Column("i64", primary_key=True), "tag_id": p.Column("i32", primary_key=True)},
    schema=SCHEMA,
)

author = Post.belongs_to(Account, from_="author_id", to="id")
editor = Post.belongs_to(Account, from_="editor_id", to="id")
posts = Account.has_many(Post, from_="id", to="author_id")
post_tags = Post.has_many(PostTag, from_="id", to="post_id")
tag_of = PostTag.belongs_to(Tag, from_="tag_id", to="id")

DDL = [
    f"CREATE SCHEMA {SCHEMA}",
    f"CREATE TYPE {SCHEMA}.mood AS ENUM ('calm', 'glad', 'sour', 'wild')",
    f"""CREATE TABLE {SCHEMA}.account (
        id int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name text NOT NULL,
        display_name text,
        mood {SCHEMA}.mood,
        tags text[] NOT NULL DEFAULT '{{}}',
        visits int4 NOT NULL DEFAULT 0,
        seq int4 GENERATED ALWAYS AS (visits + 1) STORED
    )""",
    f"""CREATE TABLE {SCHEMA}.post (
        id int8 PRIMARY KEY,
        author_id int8 NOT NULL REFERENCES {SCHEMA}.account,
        editor_id int8,
        title text NOT NULL
    )""",
    f"CREATE TABLE {SCHEMA}.tag (id int4 PRIMARY KEY, label text NOT NULL)",
    f"""CREATE TABLE {SCHEMA}.post_tag (
        post_id int8 REFERENCES {SCHEMA}.post, tag_id int4 REFERENCES {SCHEMA}.tag,
        PRIMARY KEY (post_id, tag_id)
    )""",
]

by_account = Account.col("id").asc()
by_post = Post.col("id").asc()


class ModelGraphs(unittest.IsolatedAsyncioTestCase):
    async def asyncSetUp(self):
        self.pool = p.Pool(os.environ["PGORM_TEST_DSN"], max_size=2)
        for statement in DDL:
            await self.pool.execute(p.RawSQL(statement))
        await Account.insert_many([{"name": "Ann"}, {"name": "Bob"}, {"name": "Cy"}]).execute(self.pool)
        await Post.insert_many(
            [
                {"id": 10, "author_id": 1, "editor_id": 2, "title": "a1"},
                {"id": 11, "author_id": 1, "editor_id": None, "title": "a2"},
                {"id": 12, "author_id": 2, "editor_id": 999, "title": "b1"},
            ]
        ).execute(self.pool)
        await Tag.insert_many([{"id": 1, "label": "red"}, {"id": 2, "label": "blue"}]).execute(self.pool)
        await PostTag.insert_many(
            [{"post_id": 10, "tag_id": 1}, {"post_id": 10, "tag_id": 2}, {"post_id": 12, "tag_id": 2}]
        ).execute(self.pool)

    async def asyncTearDown(self):
        await self.pool.execute(p.RawSQL(f"DROP SCHEMA {SCHEMA} CASCADE"))
        await self.pool.close()

    # [spec:pgorm:req:bindings.relations/test]
    async def test_relation_find_reads_none_for_null_keys(self):
        ann = (await Account.find().order_by(by_account).limit(1).all(self.pool))[0]
        found = await posts.find(ann).order_by(by_post).all(self.pool)
        self.assertEqual([post["title"] for post in found], ["a1", "a2"])
        a2 = await Post.find_by_key({"id": 11}).one(self.pool)
        self.assertEqual((await author.find(a2).one(self.pool))["name"], "Ann")
        self.assertEqual(await editor.find(a2).all(self.pool), [])
        self.assertEqual((posts.cardinality, author.cardinality), ("many", "one"))
        self.assertEqual(
            (author.kind, author.from_fields, author.to_fields), ("belongs_to", ("author_id",), ("id",))
        )
        self.assertIs(author.from_, Post)
        self.assertIs(author.to, Account)

    # [spec:pgorm:req:bindings.relations/test]
    async def test_load_reads_far_ends_in_one_query(self):
        accounts = await Account.find().order_by(by_account).all(self.pool)
        loaded = await posts.load(self.pool, accounts)
        self.assertEqual([[post["title"] for post in found] for found in loaded], [["a1", "a2"], ["b1"], []])
        authored = await Post.find().order_by(by_post).all(self.pool)
        self.assertEqual(
            [account["name"] for account in await author.load(self.pool, authored)], ["Ann", "Ann", "Bob"]
        )
        with self.assertRaisesRegex(p.DecodeError, "0 account rows have the key"):
            await editor.load(self.pool, authored)
        checked = [post for post in authored if post["editor_id"] != 999]
        self.assertEqual(
            [None if account is None else account["name"] for account in await editor.load(self.pool, checked)],
            ["Bob", None],
        )
        self.assertEqual(await posts.load(self.pool, []), [])
        twice = Account.has_one(Post, from_="id", to="author_id")
        with self.assertRaisesRegex(p.DecodeError, "2 post rows have the key"):
            await twice.load(self.pool, accounts)
        pairs = PostTag.belongs_to(PostTag, from_=["post_id", "tag_id"], to=["post_id", "tag_id"])
        tagged = await PostTag.find().all(self.pool)
        self.assertEqual(
            [dict(row) for row in await pairs.load(self.pool, tagged)], [dict(row) for row in tagged]
        )

    # [spec:pgorm:req:bindings.relations/test]
    def test_relation_pairs_equal_field_counts(self):
        with self.assertRaisesRegex(p.ConstructionError, "as many fields"):
            Post.belongs_to(Account, from_=["author_id", "id"], to="id")
        with self.assertRaisesRegex(p.ConstructionError, "no field 'author'"):
            Post.belongs_to(Account, from_="author", to="id")
        with self.assertRaises(ValueError):
            Post.belongs_to(Account, from_=[], to=[])
        with self.assertRaises(TypeError):
            Post.belongs_to(object(), from_="author_id", to="id")
        with self.assertRaises(TypeError):
            Post.belongs_to(Account, from_=1, to="id")
        with self.assertRaises(TypeError):
            posts.find(["id"])

    # [spec:pgorm:req:bindings.graphs/test]
    async def test_slot_kinds_decode_as_their_join(self):
        required = await Post.graph().join_one(editor).order_by(by_post).all(self.pool)
        self.assertEqual([(post["title"], account["name"]) for post, account in required], [("a1", "Bob")])
        optional = await Post.graph().join_maybe(editor).order_by(by_post).all(self.pool)
        self.assertEqual(
            [(post["title"], account and account["name"]) for post, account in optional],
            [("a1", "Bob"), ("a2", None), ("b1", None)],
        )
        roots = await Account.graph().order_by(by_account).all(self.pool)
        self.assertEqual([account["name"] for account in roots], ["Ann", "Bob", "Cy"])
        one = await Post.graph().join_one(author).where(Post.col("id").eq(12)).one(self.pool)
        self.assertEqual(one[1]["name"], "Bob")
        self.assertIsNone(await Post.graph().join_one(author).where(Post.col("id").eq(99)).optional(self.pool))
        async with await Post.graph().join_one(author).order_by(by_post).stream(self.pool) as rows:
            self.assertEqual([account["name"] async for _, account in rows], ["Ann", "Ann", "Bob"])

    # [spec:pgorm:req:bindings.graphs/test]
    async def test_graph_reads_hops_and_aliased_tables(self):
        tagged = await Post.graph().via(post_tags).join_one(tag_of).order_by(
            by_post, Tag.col("id").asc()
        ).all(self.pool)
        self.assertEqual(
            [(post["id"], tag["label"]) for post, tag in tagged], [(10, "red"), (10, "blue"), (12, "blue")]
        )
        both = await Post.graph().join_one(author).join_maybe(editor, alias="ed").order_by(by_post).all(self.pool)
        self.assertEqual(
            [(post["title"], by["name"], ed and ed["name"]) for post, by, ed in both],
            [("a1", "Ann", "Bob"), ("a2", "Ann", None), ("b1", "Bob", None)],
        )
        graph = Post.graph().join_one(author).join_maybe(editor, alias="ed")
        filtered = await graph.where(graph.col(2, "name").eq("Bob")).all(self.pool)
        self.assertEqual([post["title"] for post, _, _ in filtered], ["a1"])
        with self.assertRaisesRegex(p.ConstructionError, "already reads a table called 'account'"):
            Post.graph().join_one(author).join_maybe(editor)
        with self.assertRaisesRegex(p.ConstructionError, "starts at post_tag, which the graph does not read"):
            Account.graph().join_one(tag_of)
        with self.assertRaisesRegex(p.ConstructionError, "source 0 is post"):
            Post.graph().join_one(author).join_one(posts, alias="p", from_=0)
        with self.assertRaisesRegex(p.ConstructionError, "no source 3"):
            Post.graph().col(3, "id")
        with self.assertRaises(p.ConstructionError):
            bool(Post.graph())

    # [spec:pgorm:req:bindings.graphs/test]
    # [spec:pgorm:req:bindings.model-records/test]
    async def test_undecodable_present_slot_is_decode_error(self):
        await self.pool.execute(p.RawSQL(f"UPDATE {SCHEMA}.account SET mood = 'wild' WHERE id = 1"))
        with self.assertRaisesRegex(p.DecodeError, "'wild' is not one of the column's values"):
            await Post.graph().join_maybe(author).all(self.pool)
        with self.assertRaises(p.DecodeError):
            await Account.find().all(self.pool)

    # [spec:pgorm:req:bindings.graphs/test]
    async def test_all_grouped_gathers_each_roots_slot_records(self):
        grouped = await Account.graph().join_maybe(posts).order_by(Account.col("name").desc()).all_grouped(self.pool)
        self.assertEqual(
            [(account["name"], [post["title"] for post in found]) for account, found in grouped],
            [("Cy", []), ("Bob", ["b1"]), ("Ann", ["a1", "a2"])],
        )
        with self.assertRaisesRegex(p.ConstructionError, "exactly one slot"):
            await Account.graph().all_grouped(self.pool)
        keyless = p.Model("account", {"name": p.Column("text")}, schema=SCHEMA)
        with self.assertRaisesRegex(p.ConstructionError, "none of"):
            await keyless.graph().join_maybe(keyless.has_many(Post, from_="name", to="title")).all_grouped(self.pool)

    # [spec:pgorm:req:bindings.cursors/test]
    async def test_a_cursor_walks_rows_by_keyset(self):
        await Account.insert_many([{"name": "Ann"}, {"name": "Dee"}]).execute(self.pool)
        cursor = Account.find().cursor("name", "id")
        pages, page = [], await cursor.first(2).all(self.pool)
        while page:
            pages.append([f"{account['name']}{account['id']}" for account in page])
            last = page[-1]
            page = await cursor.after(last["name"], last["id"]).first(2).all(self.pool)
        self.assertEqual(pages, [["Ann1", "Ann4"], ["Bob2", "Cy3"], ["Dee5"]])
        self.assertEqual([a["name"] for a in await cursor.last(2).all(self.pool)], ["Cy", "Dee"])
        self.assertEqual([a["name"] for a in await cursor.desc().first(2).all(self.pool)], ["Dee", "Cy"])
        self.assertEqual([a["id"] for a in await cursor.before("Bob", 2).all(self.pool)], [1, 4])
        self.assertEqual([a["id"] for a in await cursor.desc().before("Cy", 3).all(self.pool)], [5])
        self.assertEqual(await cursor.first(0).all(self.pool), [])
        with self.assertRaisesRegex(p.ConstructionError, "boundary of 1 values does not match 2"):
            cursor.after("Ann")
        with self.assertRaises(p.ConstructionError):
            cursor.after("Ann", "x")
        with self.assertRaises(ValueError):
            cursor.first(-1)
        with self.assertRaises(TypeError):
            cursor.first("2")
        with self.assertRaisesRegex(p.ConstructionError, "at least one field"):
            Account.find().cursor()

    # [spec:pgorm:req:bindings.cursors/test]
    async def test_graph_cursor_tiebreaks_on_slot_keys(self):
        cursor = Account.graph().join_one(posts).cursor("name")
        first = await cursor.first(1).all(self.pool)
        self.assertEqual([(account["name"], post["title"]) for account, post in first], [("Ann", "a1")])
        account, post = first[0]
        resumed = await cursor.after_with(account["name"], account["id"], post["id"]).first(5).all(self.pool)
        self.assertEqual([row["title"] for _, row in resumed], ["a2", "b1"])
        skipped = await cursor.after(account["name"]).first(5).all(self.pool)
        self.assertEqual([row["title"] for _, row in skipped], ["b1"])
        self.assertIn(
            'ORDER BY "account"."name" ASC, "account"."id" ASC, "post"."id" ASC', cursor.inspect().sql
        )
        with self.assertRaisesRegex(p.ConstructionError, "1 or 3 key column"):
            cursor.after_with("Ann", 1)

    # [spec:pgorm:req:bindings.pagination/test]
    async def test_a_paginator_reads_pages_and_counts_rows(self):
        paginator = Account.find().order_by(by_account).limit(1).paginate(2)
        self.assertEqual(paginator.page_size, 2)
        self.assertEqual(await paginator.num_items_and_pages(self.pool), (3, 2))
        self.assertEqual(await paginator.num_pages(self.pool), 2)
        self.assertEqual([row["name"] for row in await paginator.fetch_page(self.pool, 1)], ["Cy"])
        self.assertEqual(await paginator.fetch_page(self.pool, 5), [])
        pages = [[row["name"] for row in page] async for page in paginator.pages(self.pool)]
        self.assertEqual(pages, [["Ann", "Bob"], ["Cy"]])
        graph_pages = Account.graph().join_one(posts).order_by(by_account, by_post).paginate(2)
        self.assertEqual(await graph_pages.num_items(self.pool), 3)
        self.assertEqual([row["title"] for _, row in await graph_pages.fetch_page(self.pool, 1)], ["b1"])
        self.assertEqual(await Account.graph().join_one(posts).count(self.pool), 3)
        self.assertEqual(await Account.find().limit(1).count(self.pool), 3)
        with self.assertRaises(ValueError):
            Account.find().paginate(0)
        with self.assertRaises(TypeError):
            Account.find().paginate(2.0)
        with self.assertRaisesRegex(ValueError, "past the offsets"):
            paginator.inspect(2**62)
        with self.assertRaises(ValueError):
            paginator.inspect(-1)

    # [spec:pgorm:req:bindings.model-reads/test]
    async def test_query_joins_relation_without_reading_it(self):
        titles = await Post.find().join(author).where(Account.col("name").eq("Bob")).all(self.pool)
        self.assertEqual([post["title"] for post in titles], ["b1"])
        edited = await (
            Post.find()
            .join(editor, kind=p.Join.Left, alias="ed")
            .where(Account.as_("ed").col("name").is_null())
            .order_by(by_post)
            .all(self.pool)
        )
        self.assertEqual([post["title"] for post in edited], ["a2", "b1"])
        tagged = await Post.select("title").join(post_tags).join(tag_of).where(Tag.col("label").eq("red")).all(self.pool)
        self.assertEqual([dict(row) for row in tagged], [{"title": "a1"}])
        with self.assertRaisesRegex(p.ConstructionError, "starts at post_tag, which the query does not read"):
            Account.find().join(tag_of)
        with self.assertRaises(ValueError):
            Post.find().join(author, kind=p.Join.Full)
        async with await Account.find().order_by(by_account).stream(self.pool) as rows:
            self.assertEqual([row["name"] async for row in rows], ["Ann", "Bob", "Cy"])
        async with self.pool.transaction() as transaction:
            with self.assertRaises(TypeError):
                await Account.find().stream(transaction)

    # [spec:pgorm:req:bindings.model-writes/test]
    async def test_writes_read_each_rows_two_versions(self):
        changes = await Account.update({"visits": 4}).where(Account.col("id").gte(2)).returning_changes(self.pool)
        self.assertEqual([(c.old["visits"], c.new["visits"], c.new["seq"]) for c in changes], [(0, 4, 5), (0, 4, 5)])
        self.assertTrue(all(isinstance(change, Change) for change in changes))
        one = await Account.update({"name": "Ann2"}).where(Account.col("id").eq(1)).returning_change(self.pool)
        self.assertEqual((one.old["name"], one.new["name"]), ("Ann", "Ann2"))
        upsert = Account.insert({"id": 1, "name": "Zed"}).on_conflict(p.ConflictTarget("id").update("name"))
        updated = await upsert.returning_upsert(self.pool)
        self.assertIsInstance(updated, Updated)
        self.assertEqual((updated.change.old["name"], updated.change.new["name"]), ("Ann2", "Zed"))
        inserted = await Account.insert({"id": 7, "name": "New"}).returning_upsert(self.pool)
        self.assertIsInstance(inserted, Inserted)
        self.assertEqual(inserted.model["name"], "New")
        held = Account.insert({"id": 7, "name": "Again"}).on_conflict(p.ConflictTarget("id").do_nothing())
        self.assertIsNone(await held.returning_upsert(self.pool))
        batch = Account.insert_many([{"id": 7, "name": "x"}, {"id": 8, "name": "y"}]).on_conflict(
            p.ConflictTarget("id").do_nothing()
        )
        self.assertEqual([row.model["name"] for row in await batch.returning_upserts(self.pool)], ["y"])
        empty = Account.insert_many([])
        self.assertEqual(
            (await empty.execute(self.pool), await empty.returning_upserts(self.pool),
             await empty.returning("id").all(self.pool), await empty.returning_upsert(self.pool)),
            (0, [], [], None),
        )
        with self.assertRaises(p.ConstructionError):
            empty.inspect()
        with self.assertRaises(p.ConstructionError):
            Account.update({"seq": 1})
        with self.assertRaises(p.UnsupportedCapabilityError):
            Account.delete().all_rows().inspect(terminal="returning_change")
        with self.assertRaises(p.UnsupportedCapabilityError):
            Account.update({"name": "x"}).all_rows().on_conflict(p.Conflict.do_nothing())
        with self.assertRaises(TypeError):
            Account.insert({"name": "x"}).on_conflict("nothing")
        with self.assertRaises(ValueError):
            Account.insert({"name": "x"}).inspect(terminal="returning")


